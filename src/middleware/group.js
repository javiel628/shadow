/**
 * True if the message came from a group chat.
 */
function isGroupChat(m) {
    return !!m.isGroup;
}

async function requireGroup(m) {
    if (!isGroupChat(m)) {
        await m.reply('⚠️ This command only works inside a group.');
        return false;
    }
    return true;
}

module.exports = { isGroupChat, requireGroup };
